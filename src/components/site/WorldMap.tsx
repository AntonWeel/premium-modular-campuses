export const MAP_H = 420;

export const px = (lon: number) => ((lon + 180) * MAP_W) / 360;
export const py = (lat: number) => ((83 - lat) * 500) / 180;
export const leftPct = (lon: number) => (px(lon) / MAP_W) * 100;
export const topPct = (lat: number) => (py(lat) / MAP_H) * 100;

